begin;

-- ----------------------------------------------------------------------------
-- 1. organizations（組織＝テナント）
-- ----------------------------------------------------------------------------
create table if not exists organizations (
  id                integer generated by default as identity primary key,
  organization_code text not null unique,
  organization_name text not null,
  is_active         boolean not null default true,
  created_at        timestamptz not null default now(),
  updated_at        timestamptz not null default now()
);

comment on table organizations is '組織（テナント）。組織 → 会社 → 拠点 の最上位。全業務データは organization_id で隔離される';

-- 既定組織（既存データの移行先 = 1 SETOLAS）とサンプル組織
insert into organizations (id, organization_code, organization_name) values
  (1, 'SETOLAS', 'SETOLAS'),
  (2, 'A-FARM',  'A-FARM'),
  (3, 'B-FARM',  'B-FARM')
on conflict (id) do nothing;

-- identity シーケンスを明示ID投入後に補正
select setval(pg_get_serial_sequence('organizations','id'),
              greatest(coalesce((select max(id) from organizations), 1), 1), true);

-- ----------------------------------------------------------------------------
-- 2. 業務テーブルへ organization_id を追加し、既存データを SETOLAS(1) へ移行
--    （products / inventory は本アプリでは items（kind='product'）/ items.stock が該当）
-- ----------------------------------------------------------------------------
do $$
declare
  t text;
  tables text[] := array[
    'users','companies','branches','doc_templates','customers','suppliers','items',
    'orders','order_lines','purchase_orders','purchase_order_lines',
    'receipts','receipt_lines','shipments','shipment_lines',
    'stock_movements','documents','number_sequences','audit_logs'
  ];
begin
  foreach t in array tables loop
    execute format('alter table %I add column if not exists organization_id integer', t);
    execute format('update %I set organization_id = 1 where organization_id is null', t);
    execute format('alter table %I alter column organization_id set default 1', t);
    execute format('alter table %I alter column organization_id set not null', t);

    if not exists (
      select 1 from pg_constraint c
      where c.conname = t || '_organization_fk' and c.conrelid = format('%I', t)::regclass
    ) then
      execute format('alter table %I add constraint %I foreign key (organization_id) references organizations(id) on delete restrict',
                     t, t || '_organization_fk');
    end if;

    execute format('create index if not exists %I on %I(organization_id)', 'idx_' || t || '_org', t);
  end loop;
end $$;

-- システム管理者フラグ（組織マスタの編集権限）
alter table users add column if not exists is_system_admin boolean not null default false;
update users set is_system_admin = true where role = 'admin' and is_system_admin = false
  and login_id = (select login_id from users order by created_at limit 1);
update users set organization_id = 1 where organization_id is null;

-- 組織 → 会社 → 拠点 の整合性（会社の組織と拠点の組織を一致させる）
create or replace function public.branch_same_org() returns trigger
language plpgsql as $$
declare c_org integer;
begin
  select organization_id into c_org from public.companies where id = new.company_id;
  if c_org is null then return new; end if;
  if new.organization_id is null then new.organization_id := c_org; end if;
  if new.organization_id <> c_org then
    raise exception '拠点の organization_id (%) が会社の organization_id (%) と一致しません', new.organization_id, c_org;
  end if;
  return new;
end $$;

drop trigger if exists trg_branches_same_org on branches;
create trigger trg_branches_same_org before insert or update on branches
  for each row execute function public.branch_same_org();

-- 帳票テンプレートも会社の組織に合わせる（全社共通=テンプレート側の組織）
create or replace function public.template_same_org() returns trigger
language plpgsql as $$
declare c_org integer;
begin
  if new.company_id is null then return new; end if;
  select organization_id into c_org from public.companies where id = new.company_id;
  if c_org is null then return new; end if;
  if new.organization_id is null then new.organization_id := c_org; end if;
  if new.organization_id <> c_org then
    raise exception 'テンプレートの organization_id が会社の organization_id と一致しません';
  end if;
  return new;
end $$;

drop trigger if exists trg_doc_templates_same_org on doc_templates;
create trigger trg_doc_templates_same_org before insert or update on doc_templates
  for each row execute function public.template_same_org();

-- ----------------------------------------------------------------------------
-- 3. アプリ設定テーブル（app_settings）へ organization_id を追加
--    organization_id = null の行は「全組織共通（システム設定）」として扱う
-- ----------------------------------------------------------------------------
alter table app_settings add column if not exists organization_id integer;
create index if not exists idx_app_settings_org on app_settings(organization_id);

-- ----------------------------------------------------------------------------
-- 4. ログインセッション（カスタムログイン + anon キーでも RLS を成立させる）
--    ・トークンはサーバー（SECURITY DEFINER 関数）だけが発行する
--    ・クライアントは x-app-token ヘッダで送信し、RLS が organization_id を解決する
-- ----------------------------------------------------------------------------
create table if not exists app_sessions (
  token           text primary key default replace(gen_random_uuid()::text, '-', ''),
  user_id         text not null references users(id) on delete cascade,
  organization_id integer not null references organizations(id),
  created_at      timestamptz not null default now(),
  expires_at      timestamptz not null default (now() + interval '12 hours'),
  revoked         boolean not null default false
);
create index if not exists idx_app_sessions_user on app_sessions(user_id);

-- 直接アクセス禁止（関数経由のみ）
alter table app_sessions enable row level security;
revoke all on app_sessions from anon, authenticated;
grant all on app_sessions to service_role;

-- ----------------------------------------------------------------------------
-- 5. 認可ヘルパー（JWT または セッショントークンから organization_id を解決）
-- ----------------------------------------------------------------------------
create or replace function public.current_org_id() returns integer
language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce(
    nullif(current_setting('request.jwt.claims', true)::jsonb #>> '{app_metadata,organization_id}', '')::int,
    nullif(current_setting('request.jwt.claims', true)::jsonb #>> '{user_metadata,organization_id}', '')::int,
    (select s.organization_id
       from public.app_sessions s
      where s.token = nullif(current_setting('request.headers', true)::jsonb ->> 'x-app-token', '')
        and s.revoked = false
        and s.expires_at > now())
  );
$$;

create or replace function public.current_user_id() returns text
language sql stable security definer set search_path = public, pg_temp as $$
  select s.user_id
    from public.app_sessions s
   where s.token = nullif(current_setting('request.headers', true)::jsonb ->> 'x-app-token', '')
     and s.revoked = false
     and s.expires_at > now();
$$;

create or replace function public.is_system_admin() returns boolean
language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce((
    select u.is_system_admin
      from public.users u
     where u.id = public.current_user_id()
        or u.id = nullif(current_setting('request.jwt.claims', true)::jsonb #>> '{app_metadata,user_id}', '')
     limit 1
  ), false);
$$;

-- ログイン（bcrypt照合 → セッショントークン発行）。users は RLS で読めないため SECURITY DEFINER
create or replace function public.app_login(p_login_id text, p_password text)
returns jsonb
language plpgsql security definer set search_path = public, extensions, pg_temp as $$
declare
  u public.users;
  org public.organizations;
  tk text;
begin
  select * into u from public.users where lower(login_id) = lower(trim(p_login_id)) limit 1;
  if u.id is null then
    return jsonb_build_object('ok', false, 'code', 'no_user', 'message', '存在しないユーザーIDです');
  end if;
  if u.enabled is false then
    return jsonb_build_object('ok', false, 'code', 'disabled', 'message', 'このユーザーは無効化されています。管理者に連絡してください');
  end if;
  if u.password_hash is null or crypt(p_password, u.password_hash) <> u.password_hash then
    return jsonb_build_object('ok', false, 'code', 'bad_password', 'message', 'パスワードが一致しません');
  end if;

  select * into org from public.organizations where id = coalesce(u.organization_id, 1);
  if org.id is null or org.is_active is false then
    return jsonb_build_object('ok', false, 'code', 'org_disabled', 'message', '所属組織が停止されています。システム管理者に連絡してください');
  end if;

  tk := replace(gen_random_uuid()::text, '-', '');
  insert into public.app_sessions(token, user_id, organization_id) values (tk, u.id, org.id);
  update public.users set last_login_at = now() where id = u.id;

  return jsonb_build_object(
    'ok', true,
    'token', tk,
    'organization_id', org.id,
    'user', (to_jsonb(u) - 'password_hash') || jsonb_build_object('organization_id', org.id)
  );
end $$;

create or replace function public.app_logout(p_token text)
returns boolean
language plpgsql security definer set search_path = public, pg_temp as $$
begin
  update public.app_sessions set revoked = true where token = p_token;
  return true;
end $$;

-- 変更時に updated_at を更新（組織マスタ）
create or replace function public.touch_updated_at() returns trigger
language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end $$;

drop trigger if exists trg_organizations_touch on organizations;
create trigger trg_organizations_touch before update on organizations
  for each row execute function public.touch_updated_at();

-- ----------------------------------------------------------------------------
-- 6. 登録時の organization_id 自動付与（クライアント入力を不要にする）
--    ・未指定なら実行中セッションの組織を採用
--    ・更新で organization_id を付け替えることは禁止（テナント越境の防止）
-- ----------------------------------------------------------------------------
create or replace function public.tenant_stamp() returns trigger
language plpgsql as $$
begin
  if new.organization_id is null then
    new.organization_id := coalesce(public.current_org_id(), 1);
  end if;
  return new;
end $$;

create or replace function public.tenant_guard() returns trigger
language plpgsql as $$
begin
  if new.organization_id is distinct from old.organization_id then
    raise exception 'organization_id は変更できません（テナント越境の禁止）';
  end if;
  return new;
end $$;

do $$
declare
  t text;
  tables text[] := array[
    'users','companies','branches','doc_templates','customers','suppliers','items',
    'orders','order_lines','purchase_orders','purchase_order_lines',
    'receipts','receipt_lines','shipments','shipment_lines',
    'stock_movements','documents','number_sequences','audit_logs'
  ];
begin
  foreach t in array tables loop
    execute format('drop trigger if exists trg_%s_stamp on %I', t, t);
    execute format('create trigger trg_%s_stamp before insert on %I for each row execute function public.tenant_stamp()', t, t);
    execute format('drop trigger if exists trg_%s_guard on %I', t, t);
    execute format('create trigger trg_%s_guard before update on %I for each row execute function public.tenant_guard()', t, t);
  end loop;
end $$;

-- ----------------------------------------------------------------------------
-- 7. RLS（Row Level Security）— DBレベルの組織隔離
-- ----------------------------------------------------------------------------
do $$
declare
  t text;
  tables text[] := array[
    'users','companies','branches','doc_templates','customers','suppliers','items',
    'orders','order_lines','purchase_orders','purchase_order_lines',
    'receipts','receipt_lines','shipments','shipment_lines',
    'stock_movements','documents','number_sequences','audit_logs'
  ];
begin
  foreach t in array tables loop
    execute format('alter table %I enable row level security', t);
    execute format('drop policy if exists tenant_isolation on %I', t);
    execute format(
      'create policy tenant_isolation on %I for all to anon, authenticated ' ||
      'using (organization_id = public.current_org_id()) ' ||
      'with check (organization_id = public.current_org_id())', t);
  end loop;
end $$;

-- 組織マスタ: 参照は自組織（またはシステム管理者）、更新はシステム管理者のみ
alter table organizations enable row level security;
drop policy if exists organizations_read on organizations;
create policy organizations_read on organizations for select to anon, authenticated
  using (id = public.current_org_id() or public.is_system_admin());
drop policy if exists organizations_insert on organizations;
create policy organizations_insert on organizations for insert to anon, authenticated
  with check (public.is_system_admin());
drop policy if exists organizations_update on organizations;
create policy organizations_update on organizations for update to anon, authenticated
  using (public.is_system_admin()) with check (public.is_system_admin());
drop policy if exists organizations_delete on organizations;
create policy organizations_delete on organizations for delete to anon, authenticated
  using (false);

-- アプリ設定: 自組織の行 + 全組織共通行（organization_id is null）のみ
alter table app_settings enable row level security;
drop policy if exists app_settings_tenant on app_settings;
create policy app_settings_tenant on app_settings for all to anon, authenticated
  using (organization_id = public.current_org_id() or organization_id is null)
  with check (organization_id = public.current_org_id() or organization_id is null);

-- anon/authenticated に実行権限（関数は SECURITY DEFINER で内部実装）
grant execute on function public.current_org_id() to anon, authenticated;
grant execute on function public.current_user_id() to anon, authenticated;
grant execute on function public.is_system_admin() to anon, authenticated;
grant execute on function public.app_login(text, text) to anon, authenticated;
grant execute on function public.app_logout(text) to anon, authenticated;

commit;

