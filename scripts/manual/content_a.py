def toc_page(M, entries, pages):
    M.h1('目次')
    M.p('本書の構成は以下のとおりです。ページ番号は本書の紙面（PDF）のページに対応します。')
    d = M.doc
    for level, num, title in entries:
        if level == 1 and num in ('', None):
            continue
        par = d.add_paragraph()
        pf = par.paragraph_format
        pf.space_after = Pt(2.5 if level == 1 else 1)
        pf.left_indent = Cm(0 if level == 1 else 0.9)
        pf.tab_stops.add_tab_stop(Cm(16.4), WD_TAB_ALIGNMENT.RIGHT, WD_TAB_LEADER.DOTS)
        r = par.add_run(title)
        set_run_font(r, 10.6 if level == 1 else 9.8, level == 1, INK if level == 1 else GRAY)
        r2 = par.add_run('\t' + str(pages.get(title, '')))
        set_run_font(r2, 9.8, level == 1, GRAY)


